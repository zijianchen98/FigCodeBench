#!/usr/bin/env python3
"""Evaluate one GT/generated-figure directory pair using one MLLM judge.
"""
from __future__ import annotations

import base64
import json
import mimetypes
import re
import time
from pathlib import Path
from typing import Any

from openai import OpenAI
from tqdm import tqdm

# ============================== Configuration ===============================
BASE_URL = "http://xxxx/v1/"
API_KEY = "sk-xxxxx"  # Replace locally; never commit a real API key.
MODEL_NAME = "xxxx"

# The script recursively matches each GT image to GEN_DIR/<same relative path>.
GT_DIR = Path("data_gt/latex/exemplary/image_base")
GEN_DIR = Path("results_final/model_name/latex/exemplary/image_base")
OUTPUT_RESULTS_FILE = Path("evaluation_results_demo.json")

MAX_RETRIES = 3
SAVE_EVERY = 1                 # Checkpoint frequency; set 1 for every image.
RESUME = True                   # Reuse existing `ok` and `missing_generated` results.
FORCE_JSON_MODE = False         # Enable only when your gateway supports response_format.
SAVE_RAW_RESPONSE = True        # Useful for auditing judge formatting failures.
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".tif", ".tiff"}


SYSTEM_PROMPT = """You are an expert acting as a rigorous judge for evaluating visualization chart plots.
The first image (Reference Image) is the ground truth plot generated by various programming languages (e.g., Python, MATLAB, R, or LaTeX). The second image (AI-Generated Image) is rendered from the code generated by an AI assistant.
Your task is to evaluate how accurately the AI-generated plot replicates the reference plot."""

USER_PROMPT = """# Scoring methodology (total: 100 points)
Evaluate the AI-generated image based on the following 5 criteria. Each criterion is worth up to 20 points.\\
1. Chart Types (20 points): Does the AI-generated image use the exact same chart types (e.g., line, bar, scatter, pie, 3D surface) and coordinate systems as the reference image?\\
2. Layout (20 points): Does the spatial arrangement of subplots, aspect ratios, and the positioning of legends or insets match the reference image exactly (e.g., number of rows and columns)?\\
3. Text Content (20 points): Does the AI-generated image precisely include all semantic text elements from the reference image (e.g., main titles, subplot titles, annotations, axis labels, and legend text), excluding axis tick numeric labels?\\
4. Data (20 points): How accurately do the data trends, distributions, number of data groups/series, and geometric mappings in the AI-generated image resemble the ground truth?\\
5. Style (20 points): Does the AI-generated image match the original in terms of visual aesthetics, including color palettes (line/fill colors), marker types (point shapes, line styles), grid presence, and background colors?\\

# Output Instructions:\\
Analyze the images step-by-step, then provide the final scores. You MUST output your response entirely in the following valid JSON format, without any surrounding markdown blocks or additional text: \\
{"evaluation":{"chart_types":{"score":0},"layout":{"score":0},"text_content":{"score":0},"data":{"score":0},"style":{"score":0}},"final_total_score":0}
The total must equal the five criterion scores."""


def encode_image(path: Path) -> str:
    """Read the original image bytes without resizing or re-encoding them."""
    mime_type = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    encoded = base64.b64encode(path.read_bytes()).decode("utf-8")
    return f"data:{mime_type};base64,{encoded}"


def extract_json_from_response(text: str) -> str:
    """Accept bare JSON or a JSON fenced code block returned by a noncompliant judge."""
    fenced = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, flags=re.DOTALL | re.IGNORECASE)
    if fenced:
        return fenced.group(1).strip()
    candidate = re.search(r"\{.*\}", text, flags=re.DOTALL)
    return candidate.group(0).strip() if candidate else text.strip()


def validate_result(data: dict[str, Any]) -> dict[str, Any]:
    dimensions = ("chart_types", "layout", "text_content", "data", "style")
    scores = {dimension: int(data["evaluation"][dimension]["score"]) for dimension in dimensions}
    if any(score < 0 or score > 20 for score in scores.values()):
        raise ValueError("A dimension score is outside [0, 20].")
    total = int(data["final_total_score"])
    if total != sum(scores.values()):
        raise ValueError(f"final_total_score={total}, but component sum={sum(scores.values())}.")
    return {"evaluation": {name: {"score": value} for name, value in scores.items()}, "final_total_score": total}


def evaluate_chart_images(client: OpenAI, gt_path: Path, generated_path: Path) -> dict[str, Any]:
    """Send the reference and generated images to exactly one MLLM judge."""
    content = [
        {"type": "text", "text": "Image 1: Reference Image (Ground Truth)"},
        {"type": "image_url", "image_url": {"url": encode_image(gt_path), "detail": "high"}},
        {"type": "text", "text": "Image 2: AI-Generated Image"},
        {"type": "image_url", "image_url": {"url": encode_image(generated_path), "detail": "high"}},
        {"type": "text", "text": USER_PROMPT},
    ]
    request: dict[str, Any] = {
        "model": MODEL_NAME,
        "messages": [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": content}],
        "temperature": 0,
    }
    if FORCE_JSON_MODE:
        request["response_format"] = {"type": "json_object"}
    response = client.chat.completions.create(**request)
    raw_response = response.choices[0].message.content or ""
    result = validate_result(json.loads(extract_json_from_response(raw_response)))
    if SAVE_RAW_RESPONSE:
        result["raw_response"] = raw_response
    return result


def atomic_save(payload: dict[str, Any]) -> None:
    OUTPUT_RESULTS_FILE.parent.mkdir(parents=True, exist_ok=True)
    temp = OUTPUT_RESULTS_FILE.with_suffix(OUTPUT_RESULTS_FILE.suffix + ".tmp")
    with temp.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
    temp.replace(OUTPUT_RESULTS_FILE)


def load_or_initialize() -> dict[str, Any]:
    if RESUME and OUTPUT_RESULTS_FILE.exists():
        with OUTPUT_RESULTS_FILE.open(encoding="utf-8") as handle:
            return json.load(handle)
    return {
        "metadata": {"judge_model": MODEL_NAME, "base_url": BASE_URL, "gt_dir": str(GT_DIR), "generated_dir": str(GEN_DIR), "image_preprocessing": "none (original image bytes)"},
        "results": {},
    }


def main() -> None:
    if not GT_DIR.is_dir():
        raise FileNotFoundError(f"GT_DIR does not exist: {GT_DIR}")
    if not GEN_DIR.is_dir():
        raise FileNotFoundError(f"GEN_DIR does not exist: {GEN_DIR}")
    client = OpenAI(base_url=BASE_URL, api_key=API_KEY)
    payload = load_or_initialize(); results: dict[str, Any] = payload.setdefault("results", {})
    gt_images = sorted(path for path in GT_DIR.rglob("*") if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES)
    pending = [path for path in gt_images if not (RESUME and results.get(path.relative_to(GT_DIR).as_posix(), {}).get("status") in {"ok", "missing_generated"})]
    print(f"Found {len(gt_images)} GT images; evaluating {len(pending)} pending pairs with {MODEL_NAME}.")

    for index, gt_path in enumerate(tqdm(pending, desc="Single-judge evaluation"), start=1):
        relative_path = gt_path.relative_to(GT_DIR).as_posix(); generated_path = GEN_DIR / relative_path
        record: dict[str, Any] = {"gt_path": str(gt_path), "generated_path": str(generated_path)}
        if not generated_path.is_file():
            results[relative_path] = {**record, "status": "missing_generated", "evaluation": None}
        else:
            for attempt in range(1, MAX_RETRIES + 1):
                try:
                    evaluation = evaluate_chart_images(client, gt_path, generated_path)
                    results[relative_path] = {**record, "status": "ok", **evaluation}
                    break
                except Exception as error:
                    if attempt == MAX_RETRIES:
                        results[relative_path] = {**record, "status": "error", "error": f"{type(error).__name__}: {error}", "evaluation": None}
                    else:
                        time.sleep(2 ** (attempt - 1))
        if index % SAVE_EVERY == 0:
            atomic_save(payload)
    atomic_save(payload)
    ok_count = sum(row.get("status") == "ok" for row in results.values())
    print(f"Completed. {ok_count}/{len(gt_images)} image pairs judged. Results: {OUTPUT_RESULTS_FILE}")


if __name__ == "__main__":
    main()
